import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react"
import userEvent from "@testing-library/user-event"
import { afterEach, beforeEach, expect, it, vi } from "vitest"
const mocks = vi.hoisted(() => ({ permissions: new Set<string>(), status: vi.fn(), remoteConfig: vi.fn(), update: vi.fn(), push: vi.fn(), search: vi.fn() }))
vi.mock("@/lib/backend-client", () => ({ hasBackendPermission: (permission: string) => mocks.permissions.has(permission) }))
vi.mock("@/services/firebase.service", () => ({ firebaseService: { status: mocks.status, remoteConfig: mocks.remoteConfig, updateRemoteConfig: mocks.update, sendTestPush: mocks.push, searchTestRecipients: mocks.search } }))
vi.mock("@/lib/toast", () => ({ showToast: { success: vi.fn(), error: vi.fn() } }))
import FirebaseSettingsPage from "./page"
const template = { parameters: {} }
beforeEach(() => {
  mocks.permissions = new Set(["firebase.status.read", "firebase.config.manage", "firebase.push.test"])
  mocks.status.mockResolvedValue({ enabled: true, project_id: "test-project", active_device_count: 12, stale_device_count: 2, platforms: { android: 12 }, delivery_reporting: "Provider acceptance does not confirm device delivery." })
  mocks.remoteConfig.mockResolvedValue({ template, etag: "version-1" })
  mocks.update.mockResolvedValue({ template, etag: "version-2" })
  mocks.push.mockResolvedValue({ attempted: 1, accepted: 0, validated: 1, failed: 0, devices: [{ device_id: "device-1", platform: "android", state: "validated" }] })
  mocks.search.mockResolvedValue([])
})
afterEach(() => { cleanup(); vi.clearAllMocks(); vi.restoreAllMocks() })
it("shows a retryable load error and recovers the configuration workspace", async () => {
  mocks.status.mockRejectedValueOnce(new Error("Firebase unavailable"))
  render(<FirebaseSettingsPage />)
  expect(await screen.findByRole("alert")).toHaveTextContent("Firebase unavailable")
  expect(screen.queryByRole("textbox", { name: "Remote Config template" })).not.toBeInTheDocument()
  await userEvent.click(screen.getByRole("button", { name: "Try again" }))
  expect(await screen.findByRole("textbox", { name: "Remote Config template" })).toHaveValue(JSON.stringify(template, null, 2))
  expect(screen.getByText("test-project")).toBeInTheDocument()
})
it("preserves validation, publish confirmation and optimistic concurrency", async () => {
  const confirm = vi.spyOn(window, "confirm").mockReturnValue(false)
  render(<FirebaseSettingsPage />)
  await screen.findByRole("textbox", { name: "Remote Config template" })
  await userEvent.click(screen.getByRole("button", { name: "Publish" }))
  expect(mocks.update).not.toHaveBeenCalled()
  await userEvent.click(screen.getByRole("button", { name: "Validate" }))
  await waitFor(() => expect(mocks.update).toHaveBeenCalledWith(template, "version-1", true))
  confirm.mockReturnValue(true)
  await userEvent.click(screen.getByRole("button", { name: "Publish" }))
  await waitFor(() => expect(mocks.update).toHaveBeenLastCalledWith(template, "version-2", false))
})
it("validates push separately from sending and preserves the send confirmation", async () => {
  vi.spyOn(window, "confirm").mockReturnValue(false)
  render(<FirebaseSettingsPage />)
  await userEvent.click(await screen.findByRole("button", { name: "Validate delivery" }))
  await waitFor(() => expect(mocks.push).toHaveBeenCalledWith(expect.objectContaining({ current_user: true, dry_run: true })))
  expect(await screen.findByText("validated")).toBeInTheDocument()
  mocks.push.mockClear()
  await userEvent.click(screen.getByRole("button", { name: "Send push" }))
  expect(mocks.push).not.toHaveBeenCalled()
})
it("does not invent channel-health statistics when only push-test access is granted", async () => {
  mocks.permissions = new Set(["firebase.push.test"])
  render(<FirebaseSettingsPage />)
  expect(await screen.findByRole("button", { name: "Validate delivery" })).toBeInTheDocument()
  expect(mocks.status).not.toHaveBeenCalled()
  expect(screen.queryByText("Live channel health")).not.toBeInTheDocument()
  expect(screen.queryByText("Active devices")).not.toBeInTheDocument()
  expect(screen.queryByRole("textbox", { name: "Remote Config template" })).not.toBeInTheDocument()
})
it("shows the disabled service state without offering publish or send actions", async () => {
  mocks.status.mockResolvedValue({ enabled: false })
  render(<FirebaseSettingsPage />)
  expect(await screen.findByText(/Firebase is disabled/)).toBeInTheDocument()
  expect(mocks.remoteConfig).not.toHaveBeenCalled()
  expect(screen.queryByRole("button", { name: "Publish" })).not.toBeInTheDocument()
  expect(screen.queryByRole("button", { name: "Send push" })).not.toBeInTheDocument()
})
it("makes no service calls without Firebase permissions", async () => {
  mocks.permissions = new Set()
  render(<FirebaseSettingsPage />)
  expect(await screen.findByText(/You do not have permission/)).toBeInTheDocument()
  expect(mocks.status).not.toHaveBeenCalled()
  expect(mocks.remoteConfig).not.toHaveBeenCalled()
})

it("preserves unpublished edits through validation and supports resetting them before refresh", async () => {
  const candidate = { parameters: { feature: { defaultValue: { value: "true" } } } }
  mocks.update.mockResolvedValueOnce({ template: candidate, etag: "version-2" })
  render(<FirebaseSettingsPage />)
  const editor = await screen.findByRole("textbox", { name: "Remote Config template" })
  fireEvent.change(editor, { target: { value: JSON.stringify(candidate, null, 2) } })
  expect(screen.getByRole("button", { name: "Refresh" })).toBeDisabled()
  await userEvent.click(screen.getByRole("button", { name: "Validate" }))
  await waitFor(() => expect(mocks.update).toHaveBeenCalledWith(candidate, "version-1", true))
  expect(screen.getByRole("button", { name: "Reset edits" })).toBeEnabled()
  expect(screen.getByRole("button", { name: "Refresh" })).toBeDisabled()
  await userEvent.click(screen.getByRole("button", { name: "Reset edits" }))
  expect(editor).toHaveValue(JSON.stringify(template, null, 2))
  expect(screen.getByRole("button", { name: "Refresh" })).toBeEnabled()
})
